"""Compact Sonor Force 3001 recordings, Sam Greene / kinwie, CC BY-SA 4.0.
Offline preparation only. The derived WAV recordings retain the same licence.
"""
import concurrent.futures,hashlib,json,pathlib,subprocess,tempfile,urllib.parse,urllib.request,wave
import numpy as np
ROOT=pathlib.Path(__file__).resolve().parents[1]/'src/audio/samples/sonor'
ROOT.mkdir(exist_ok=True)
REV='ef3e32058924ed1c3335e86d03094d3f310a9104'
BASE=f'https://raw.githubusercontent.com/sfzinstruments/SamsSonor/{REV}/'
specs=[];groups={}
def add(group,names,tail):
 ids=[]
 for i,name in enumerate(names,1):
  id='sonor'+group[0].upper()+group[1:]+str(i);ids.append(id);specs.append((id,group,name+'.flac',tail))
 groups[group]=ids
add('kickSoft',['KickSamples#1','KickSamples#2'],.24)
add('kick',['KickSamples#4','KickSamples#5'],.24)
add('kickAccent',['KickSamples#6','KickSamples#7'],.24)
add('snareGhost',['SnareLeftHand','SnareRightHand'],.35)
add('snareSoft',['SnareLeftHand#2','SnareRightHand#2'],.45)
add('snareMid',['SnareLeftHand#4','SnareRightHand#4'],.55)
add('snare',['SnareLeftHand#6','SnareRightHand#7'],.6)
add('snareAccent',['SnareLeftHand#9','SnareRightHand#8'],.65)
add('hatSoft',['HHClosed#1','HHClosed'],.18)
add('hat',['HHClosed#3','HHClosed#2'],.22)
add('hatAccent',['HHClosed#4','HHClosed#6'],.25)
add('hatOpen',['HHHalfOpen#3','HHHalfOpen#4'],.7)
add('hatPedal',['HHPedal#2','HHPedal#3'],.3)
add('rideSoft',['Ride','Ride#1'],1.9)
add('ride',['Ride#2','Ride#3'],2.1)
add('rideAccent',['Ride#4'],2.2)
add('rideBellSoft',['RideBell'],1.5)
add('rideBell',['RideBell#1','RideBell#2'],1.8)
add('crashSoft',['CrashTip','CrashTip#1'],1.9)
add('crash',['CrashTip#2','CrashTip#3'],2.2)
add('tomHighSoft',['TomHigh#1'],.5)
add('tomHigh',['TomHigh#3','TomHigh#4'],.65)
add('tomLowSoft',['TomLow#1'],.6)
add('tomLow',['TomLow#4','TomLow#5'],.8)
add('rim',['SnareSamples#9'],.3)
groups['flatRide']=groups['rideSoft']
cache={f['id']:f for f in json.loads((ROOT/'sources.json').read_text())['files']} if (ROOT/'sources.json').exists() else {}
def prepare(spec):
 id,group,name,tail=spec;dest=ROOT/(id+'.wav')
 if id in cache and dest.exists() and hashlib.sha256(dest.read_bytes()).hexdigest()==cache[id]['sha256']:return cache[id]
 path='Samples/'+name;url=BASE+urllib.parse.quote(path);raw=urllib.request.urlopen(url,timeout=45).read()
 kick=group.startswith('kick');snare=group.startswith('snare');tom=group.startswith('tom')
 filters='highpass=f=48,equalizer=f=95:t=q:w=1:g=-3,equalizer=f=3200:t=q:w=1:g=2,lowpass=f=14500' if kick else 'highpass=f=110,equalizer=f=350:t=q:w=1:g=-2,lowpass=f=14500' if snare else 'highpass=f=55,equalizer=f=350:t=q:w=1:g=-2,lowpass=f=14500' if tom else 'highpass=f=250,lowpass=f=14500'
 with tempfile.TemporaryDirectory() as tmp:
  src=pathlib.Path(tmp)/'source.flac';src.write_bytes(raw)
  data=subprocess.check_output(['ffmpeg','-v','error','-i',str(src),'-ac','1','-ar','32000','-af',filters,'-f','f32le','-']);x=np.frombuffer(data,dtype='<f4').copy()
 peak=max(abs(x));start=max(0,int(np.flatnonzero(abs(x)>peak*.003)[0])-16);x=x[start:start+round(tail*32000)]
 if kick:
  times=np.arange(len(x))/32000;x*=np.where(times<.055,1,np.exp(-(times-.055)/.055))
 edge=min(960,len(x)//4);x[:16]*=np.arange(16)/16;x[-edge:]*=np.linspace(1,0,edge);x*=.85/max(abs(x));pcm=np.round(x*32767).astype('<i2')
 with wave.open(str(dest),'wb') as out:out.setnchannels(1);out.setsampwidth(2);out.setframerate(32000);out.writeframes(pcm.tobytes())
 return dict(id=id,group=group,path=path,revision=REV,license='CC-BY-SA-4.0',source_sha256=hashlib.sha256(raw).hexdigest(),sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),bytes=dest.stat().st_size,duration=len(x)/32000,filters=filters,onsetTrimFrames=start)
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:files=list(pool.map(prepare,specs))
(ROOT/'LICENSE').write_bytes(urllib.request.urlopen(BASE+'LICENSE',timeout=30).read().rstrip()+b'\n')
(ROOT/'sources.json').write_text(json.dumps(dict(repository='sfzinstruments/SamsSonor',revision=REV,license='CC-BY-SA-4.0',attribution='Sonor Force 3001 recorded by Sam Greene; SFZ/FLAC mapping and conversion by kinwie.',processing='Selected original recorded velocity layers; paired left/right snare hands. Mono 32 kHz PCM16, onset trim, gentle low-mid cuts, edge fades and peak normalization. Kick-only short decay. Derived recordings distributed under CC BY-SA 4.0.',files=files),indent=2)+'\n')
(ROOT.parent.parent/'sonor-groups.js').write_text('// Worklet-safe Sonor recording groups; generated by prepare-sonor-drums.py.\nexport const SONOR_DRUM_GROUPS='+json.dumps(groups)+';\n')
(ROOT.parent.parent/'sonor-samples.js').write_text('// Literal URLs for Vite; generated by prepare-sonor-drums.py.\nexport const SONOR_SAMPLE_FILES={\n'+''.join(f' {f["id"]}:new URL("./samples/sonor/{f["id"]}.wav",import.meta.url),\n' for f in files)+'};\n')
print(f'Prepared {len(files)} Sonor recordings, {sum(f["bytes"] for f in files)/1048576:.2f} MiB',flush=True)
